-- GigBooks: copy the database STRUCTURE (no data) from production to dev.
--
-- 1. Run this in the PRODUCTION project's SQL Editor.
-- 2. It returns one cell called "dev_setup_sql". Copy its whole contents.
-- 3. Paste that into the DEV project's SQL Editor and click Run.
--
-- It reads only system catalogs and never returns or changes any user data.
-- Safe to run again; the script it produces can also be re-run.

with
ext as (
  select string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname) s
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname not in ('plpgsql') and n.nspname not in ('pg_catalog')
),
enums as (
  select string_agg(format('do $e$ begin create type public.%I as enum (%s); exception when duplicate_object then null; end $e$;',
    t.typname, (select string_agg(quote_literal(x.enumlabel), ', ' order by x.enumsortorder) from pg_enum x where x.enumtypid = t.oid)), E'\n') s
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
),
seqs as (
  select string_agg(format('create sequence if not exists public.%I;', c.relname), E'\n') s
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')   -- identity columns make their own
),
funcs as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.oid) s
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')   -- skip extension functions
),
tbls as (
  select string_agg(format('create table if not exists public.%I (%s);', c.relname,
    (select string_agg(
        format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
        || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                else '' end
        || case when a.attnotnull then ' not null' else '' end,
        ', ' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)), E'\n' order by c.oid) s
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
cons as (
  select string_agg(format('do $c$ begin alter table public.%I add constraint %I %s; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $c$;',
    c.relname, con.conname, pg_get_constraintdef(con.oid)), E'\n'
    order by case con.contype when 'p' then 0 when 'u' then 1 when 'x' then 2 when 'c' then 3 else 4 end, c.oid) s
  from pg_constraint con join pg_class c on c.oid = con.conrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and con.contype in ('p', 'u', 'c', 'f', 'x')
),
idx as (
  select string_agg(replace(pg_get_indexdef(i.indexrelid), 'CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ') || ';', E'\n') s
  from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
    and pg_get_indexdef(i.indexrelid) like 'CREATE INDEX %'
),
uidx as (
  select string_agg(replace(pg_get_indexdef(i.indexrelid), 'CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ') || ';', E'\n') s
  from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
    and pg_get_indexdef(i.indexrelid) like 'CREATE UNIQUE INDEX %'
),
vws as (
  select string_agg(format('create or replace view public.%I%s as %s', c.relname,
    case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
    pg_get_viewdef(c.oid)), E'\n\n' order by c.oid) s
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
trg as (
  select string_agg(format('drop trigger if exists %I on %I.%I;', t.tgname, n.nspname, c.relname) || E'\n' || pg_get_triggerdef(t.oid) || ';', E'\n' order by t.oid) s
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
),
rls as (
  select string_agg(format('alter table public.%I enable row level security;', c.relname)
    || case when c.relforcerowsecurity then format(' alter table public.%I force row level security;', c.relname) else '' end, E'\n') s
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
),
pol as (
  select string_agg(format('drop policy if exists %I on %I.%I;', p.policyname, p.schemaname, p.tablename) || E'\n'
    || format('create policy %I on %I.%I as %s for %s to %s', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
       array_to_string(array(select case when r = 'public' then 'public' else quote_ident(r) end from unnest(p.roles) r), ', '))
    || coalesce(' using (' || p.qual || ')', '') || coalesce(' with check (' || p.with_check || ')', '') || ';', E'\n')
  s
  from pg_policies p
  where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
),
bkt as (
  select string_agg(format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
    b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'),
    coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null')), E'\n') s
  from storage.buckets b
)
select concat_ws(E'\n\n',
  '-- GigBooks dev database structure, copied from production on ' || now()::date || '. Structure only, no data.',
  'set check_function_bodies = off;',
  '-- Extensions', (select s from ext),
  '-- Types', (select s from enums),
  '-- Sequences', (select s from seqs),
  '-- Functions', (select s from funcs),
  '-- Tables', (select s from tbls),
  '-- Keys and checks', (select s from cons),
  '-- Indexes', (select s from uidx), (select s from idx),
  '-- Views', (select s from vws),
  '-- Triggers', (select s from trg),
  '-- Row level security', (select s from rls),
  '-- Policies', (select s from pol),
  '-- Storage buckets', (select s from bkt),
  'notify pgrst, ''reload schema'';'
) as dev_setup_sql;
